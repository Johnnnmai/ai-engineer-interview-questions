def zh_alternates(slug=None):
    """hreflang link tags for an English/Chinese pair. slug=None pairs /questions/ with /zh/."""
    if slug is not None and slug not in ZH_SLUGS:
        return ""
    en = f"{ZH_SITE}/questions/{slug}/" if slug else f"{ZH_SITE}/questions/"
    zh = f"{ZH_SITE}/zh/{slug}/" if slug else f"{ZH_SITE}/zh/"
